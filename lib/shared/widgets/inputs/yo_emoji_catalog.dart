/// The emoji vocabulary offered by [YoEmojiPicker].
///
/// ## Why this ships as data instead of a package
///
/// Every Flutter emoji-picker package either bundles its own font, its own
/// asset blob, or a transitive plugin. YO Voice renders emoji with the
/// platform font, so the only thing actually missing was the vocabulary and
/// its search keywords — a plain Dart list, tree-shaken like the translation
/// catalogs, with no new dependency and no new resolution.
///
/// ## Platform support boundary
///
/// The entries below are bounded to **Unicode Emoji 5.0 (2017)** and earlier.
/// That is deliberate and it is the binding constraint, not a rough guess:
///
/// * iOS 15 ships Emoji 13.1 (14.0 from 15.4), so it covers everything here.
/// * Android 8.0 — the oldest release YO Voice supports — ships Emoji 5.0.
///
/// Android 8.0 is therefore the ceiling. Anything newer (🥰 🥺 🥳 🧊 🧁 from
/// Emoji 11, 🦩 🪀 from Emoji 12, 🥲 from Emoji 13, 🫠 from Emoji 14) renders
/// as a tofu box on a device that never received a font update, so none of it
/// is listed. Raising the ceiling is a one-line comment change here once the
/// minimum supported Android version moves — the picker code itself is
/// version-agnostic.
///
/// Skin-tone modifiers and gender ZWJ variants are intentionally out of scope
/// for this pass: they multiply the grid by five to twelve and deserve their
/// own selector rather than being smuggled in as extra cells.
library;

import 'package:flutter/foundation.dart';

/// A single selectable emoji together with everything needed to find it.
///
/// [name] doubles as the accessibility label, so it is a human phrase rather
/// than a Unicode identifier.
@immutable
class YoEmoji {
  const YoEmoji(
    this.char,
    this.name,
    this.namePolish, [
    this.keywords = '',
    this.keywordsPolish = '',
  ]);

  /// The emoji itself, as it is inserted into the composer.
  final String char;

  /// English display name, also used as the semantic label.
  final String name;

  /// Polish display name, also used as the semantic label in Polish.
  final String namePolish;

  /// Space-separated English search terms beyond [name].
  final String keywords;

  /// Space-separated Polish search terms beyond [namePolish].
  final String keywordsPolish;

  @override
  bool operator ==(Object other) =>
      other is YoEmoji && other.char == char;

  @override
  int get hashCode => char.hashCode;
}

