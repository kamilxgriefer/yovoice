final Map<String, String> _searchHaystacks = {
  for (final emoji in yoEmojiCatalog)
    emoji.char: yoFoldSearchTerm(
      '${emoji.name} ${emoji.namePolish} '
      '${emoji.keywords} ${emoji.keywordsPolish}',
    ),
};

/// Emoji whose name or keywords — English or Polish — match [query].
///
/// An empty or whitespace-only query returns the whole catalogue, so the caller
/// can use one code path for "searching" and "browsing".
List<YoEmoji> yoSearchEmoji(String query) {
  final needle = yoFoldSearchTerm(query.trim());
  if (needle.isEmpty) return yoEmojiCatalog;
  return [
    for (final emoji in yoEmojiCatalog)
      if (_searchHaystacks[emoji.char]!.contains(needle)) emoji,
  ];
}
