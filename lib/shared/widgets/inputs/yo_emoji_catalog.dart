/// Lowercases and strips Polish diacritics so that "zolw", "żółw" and "Żółw"
/// are the same query. Without this, searching Polish on an English keyboard —
/// which is what most people actually type on — finds nothing.
String yoFoldSearchTerm(String value) {
  final buffer = StringBuffer();
  for (final rune in value.toLowerCase().runes) {
    final character = String.fromCharCode(rune);
    buffer.write(_polishFolding[character] ?? character);
  }
  return buffer.toString();
}

