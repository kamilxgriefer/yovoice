const _pluralCategories = <String>[
  'zero',
  'one',
  'two',
  'few',
  'many',
  'other',
];

Map<String, String> _withPlurals(
  Map<String, String> translations,
  List<String> conversations,
  List<String> messages,
) {
  assert(conversations.length == _pluralCategories.length);
  assert(messages.length == _pluralCategories.length);
  return Map<String, String>.unmodifiable(<String, String>{
    ...translations,
    for (var index = 0; index < _pluralCategories.length; index++)
      '{count} unread conversation.${_pluralCategories[index]}':
          conversations[index],
    for (var index = 0; index < _pluralCategories.length; index++)
      '{count} unread message.${_pluralCategories[index]}': messages[index],
  });
}

