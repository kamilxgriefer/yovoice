final localizedExtendedLanguageNames =
    Map<String, Map<String, String>>.unmodifiable(<String, Map<String, String>>{
      for (final entry in _localizedExtendedLanguageNameValues.entries)
        entry.key: _languageNameMap(entry.key, entry.value),
    });

Map<String, String> _languageNameMap(String localeKey, List<String> values) {
  if (values.length != _extendedLanguageNameKeys.length) {
    throw StateError(
      '$localeKey has ${values.length} extended language names; '
      '${_extendedLanguageNameKeys.length} are required.',
    );
  }
  return Map<String, String>.unmodifiable(
    Map<String, String>.fromIterables(_extendedLanguageNameKeys, values),
  );
}
