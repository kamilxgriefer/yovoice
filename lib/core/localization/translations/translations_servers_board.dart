/// (`lib/features/servers/presentation/servers_board_copy.dart` and, for the
/// lines the board reuses, `server_localized_copy.dart`); this module gives
/// every other selectable locale an explicit translation, so nothing on the
/// board falls back to English.
///
/// Two kinds of key live here:
///
/// * The final English phrase or template (`Your servers`,
///   `{count} people`), resolved by `AppLocalizations.text` / `.template`.
/// * `serversBoard.*` context keys for short words whose meaning depends on
///   the board ("View" the public card's action, "live" the row's lamp,
///   "Show all" / "Show fewer" under the list, "Paste" the clipboard
///   action), resolved by `AppLocalizations.contextualText`.
///
/// `Create server` and the keys from `Servers` down are Servers copy that
/// existed before the board and had no catalog entry (`Servers`, the kind
/// line — `Community`, `Private server`, `Podcast server`…, the member count
/// and `Manage server`). The board renders them on every row and card, so
/// they are translated here; every other screen that uses the same English
/// phrase now resolves the same word. `Servers` repeats the dock's own label
/// for each locale.
///
/// The member count has two forms in the app (`{count} person` for one,
/// `{count} people` otherwise). Languages whose noun changes with the number
/// in more than two ways use a count-neutral form ("Участников: 5") rather
/// than a wrong case.
///
/// `{count} person in the server` / `{count} people in the server` are the
/// phone workspace header's line (`serverMembersInServer`). It used to embed
/// the count phrase in an English sentence; with the count translated that
/// would read "12 Personen in the server", so the line is a pair of whole
/// templates and lives here beside the count it is built from.
///
/// "YO Voice" stays as written. Every value keeps exactly the placeholders
/// of its key (`test/servers_board_localization_test.dart`).
