/// Copy for notifications that follow what you follow (ADR-237) and the
/// server's push copy in the recipient's language.
///
/// Three groups of key live here:
///
/// * The notification titles the bell has always shown — a friend request, a
///   server invitation, a call, a mention, an unlocked achievement — which
///   were never catalogued, so outside English and Polish they stayed
///   English. `NotificationCopy` resolves them, and the same entries are
///   exported to `functions/notifications/push_copy.json`
///   (`test/push_copy_export_test.dart`), so a push says exactly what the
///   bell row says in the recipient's language.
/// * The new "a Page you follow published a post" title, and the
///   lock-screen sentences only a push shows (`NotificationPushCopy`): the
///   generic body, the private call notices and the video-call variants.
/// * Notification settings, the whole screen: the "Following" group, its two
///   switches and the daily-cap helper line, and every group title and
///   switch label that was there before but had never been catalogued.
///   `notifyFollow.*` and `notifyPrefs.*` are context keys: "Following",
///   "Servers", "Calls", "Messages", "Mentions" and "Replies" are single
///   words that mean other things elsewhere, so their translations here do
///   not leak into other screens.
///
/// English and Polish are authored at the call sites; this module gives every
/// other selectable locale an explicit translation, so none of these strings
/// falls back to English. "YO Voice" and "LIVE" stay as written. Languages
/// whose past tense is gendered use a present-tense or noun form, because
/// the actor's gender is unknown.
///
/// Every value keeps exactly the placeholders of its key
/// (`test/notify_follow_localization_test.dart`).
