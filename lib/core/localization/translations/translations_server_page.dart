/// Copy for the server page (`Strona serwera`, ADR-240): what a server opens
/// on — the cover, the name and its meta line, the actions, the template's
/// main thing, then conversations, voice, events and the way to every channel.
///
/// English and Polish are authored at the call sites
/// (`server_page_copy.dart` for what the page adds, `server_localized_copy.dart`
/// for the Servers phrases it reuses); this module gives every other
/// selectable locale an explicit translation, so nothing the page shows falls
/// back to English.
///
/// Two kinds of key live here:
///
/// * The final English phrase or template (`All channels ({count})`,
///   `Live since {time}`), resolved by `AppLocalizations.text` / `.template`.
///   Besides the page's own phrases these are the existing Servers phrases
///   the page renders — the kind and privacy words of the meta line, `Invite`,
///   the live and quiet lines, the join words, the event actions and the
///   session card's labels — which had no catalog entry before and now
///   resolve the same way wherever the Servers surface uses them. (`Share`,
///   `Microphone`, `Connecting…` and `Joining…` already had entries in other
///   modules and are not repeated here: a key lives in exactly one module.)
/// * `serverPage.*` context keys for short words whose form depends on where
///   they stand: `public` inside the meta line (a lower-case adjective),
///   `today` / `tomorrow` inside "tomorrow · Scena LIVE", the section heading
///   `Voice` (not the channel kind) and the short `Join` on a voice row.
///   They are resolved by `AppLocalizations.contextualText`.
///
/// `LIVE` in `Next LIVE` and `Go LIVE` is the product's own word for a
/// broadcast and stays as written, as Polish keeps it (`Następny LIVE`,
/// `Nadaj LIVE`); the live marker itself (`LIVE` → `NA ŻYWO`) is translated.
/// Every value keeps exactly the placeholders of its key
/// (`test/server_page_localization_test.dart`).
